let currentLang = localStorage.getItem('pbv-lang') || 'it';

function t(key) {
  return I18N[currentLang]?.[key] || I18N['it'][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('pbv-lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  // Re-render current view if app is initialized
  if (window.App && window.App.renderCurrent) {
    window.App.renderCurrent();
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = t(key);
    if (text) el.textContent = text;
  });
  // Update active lang button
  document.querySelectorAll('.langs button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  applyTranslations();
  document.querySelectorAll('.langs button').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
});
